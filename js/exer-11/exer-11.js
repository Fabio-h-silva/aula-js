let num_um = Number(prompt("Digite o primeiro número:"))
let num_dois = Number(prompt("Digite o segundo número:"))


if (num_um > num_dois) {
    alert(`O primeiro número é o maior: ${num_um}`)
} else if (num_um < num_dois) {
    alert(`O segundo número é o maior: ${num_dois}`)
} else {
    alert(`O primeiro e segundo numero são iguais: ${num_um}`)
}